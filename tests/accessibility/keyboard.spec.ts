import { mkdirSync, writeFileSync } from "node:fs"
import path from "node:path"
import type { Page, TestInfo } from "@playwright/test"
import { accountMenu, evidenceDir, expect, loginWithForm, SIGN_OUT_RSC_404, test, titleField } from "../e2e/lib/fixtures"
import { tabTo } from "./keyboard-helpers"

// Cada cierre abre su propia sesión: signOut global revoca las de los otros motores.
test.use({ account: "anon" })

async function ready(page: Page) {
  await expect(page.getByRole("heading", { level: 1 })).toBeVisible()
  await page.waitForLoadState("networkidle")
}
function save(info: TestInfo, name: string, result: unknown) {
  const evidence = evidenceDir("2026-10-24/O11/exp-03")
  mkdirSync(evidence, { recursive: true })
  writeFileSync(path.join(evidence, `${info.project.name}-${name}.json`), JSON.stringify(result, null, 2) + "\n")
}

test("teclado: alta, búsqueda, selección, movimiento, edición, foco y cierre de sesión", async ({ page, stack, data, guard }, info) => {
  const slug = data.slug("teclado")
  const title = data.marked(`Libro ${slug}`)
  const shelf = await data.shelf("a", `Destino ${slug}`)
  await page.goto("/login")
  await loginWithForm(page, stack, "a")
  await page.waitForURL((url) => url.pathname === "/")
  await page.goto("/books/add")
  await ready(page)
  await tabTo(page, page.getByRole("tab", { name: "Buscar por ISBN" }))
  await page.keyboard.press("ArrowRight")
  await expect(page.getByRole("tab", { name: "Entrada manual" })).toHaveAttribute("aria-selected", "true")
  await tabTo(page, titleField(page))
  await page.keyboard.type(title)
  await tabTo(page, page.getByRole("button", { name: "Agregar a la biblioteca" }))
  await page.keyboard.press("Enter")
  await page.waitForURL(/\/book\//)
  await ready(page)
  const id = new URL(page.url()).pathname.split("/").pop()
  if (!id) throw new Error("No hay ID de ficha tras el alta")
  await tabTo(page, page.getByRole("button", { name: "Editar ficha" }))
  await page.keyboard.press("Enter")
  await expect(titleField(page)).toBeFocused()
  await page.keyboard.press("End")
  await page.keyboard.type(" revisado")
  await tabTo(page, page.getByRole("button", { name: "Guardar cambios" }))
  await page.keyboard.press("Enter")
  await expect(page.getByRole("button", { name: "Editar ficha" })).toBeFocused()
  await expect(page.getByRole("heading", { level: 1 })).toHaveText(`${title} revisado`)
  await tabTo(page, page.getByRole("link", { name: "Volver a libros" }))
  await page.keyboard.press("Enter")
  await ready(page)
  await tabTo(page, page.getByRole("textbox", { name: "Buscar por título, autor o ISBN" }))
  await page.keyboard.type(slug)
  await expect(page.getByText("1 resultado", { exact: true })).toBeVisible()
  const sort = page.getByRole("columnheader", { name: /Título/ })
  await expect(sort).toHaveAttribute("aria-sort", "ascending")
  await tabTo(page, sort.getByRole("button"))
  await page.keyboard.press("Enter")
  await expect(sort).toHaveAttribute("aria-sort", "descending")
  await page.waitForLoadState("networkidle")
  await page.keyboard.press("Enter")
  await expect(sort).toHaveAttribute("aria-sort", "ascending")
  await page.waitForLoadState("networkidle")
  await tabTo(page, page.getByRole("checkbox", { name: `Seleccionar ${title} revisado`, exact: true }))
  await page.keyboard.press("Space")
  await tabTo(page, page.getByRole("combobox", { name: "Estantería de destino" }))
  await page.keyboard.press("Enter")
  const options = page.getByRole("option")
  const index = (await options.allTextContents()).findIndex((label) => label.trim() === data.marked(`Destino ${slug}`))
  expect(index).toBeGreaterThanOrEqual(0)
  await page.keyboard.press("Home")
  await expect(options.first()).toBeFocused()
  for (let position = 1; position <= index; position++) {
    await page.keyboard.press("ArrowDown")
    await expect(options.nth(position)).toBeFocused()
  }
  await page.keyboard.press("Enter")
  await expect(page.getByRole("combobox", { name: "Estantería de destino" })).toBeFocused()
  await expect(page.getByRole("listbox")).toHaveCount(0)
  await tabTo(page, page.getByRole("button", { name: "Mover 1 libro", exact: true }))
  await page.keyboard.press("Enter")
  await expect.poll(async () => (await stack.sql`select shelf_id from biblib.books where id = ${id}`)[0]?.shelf_id).toBe(shelf)
  await expect(page.getByRole("checkbox", { name: `Seleccionar ${title} revisado`, exact: true })).not.toBeChecked()
  await expect(page.getByRole("checkbox", { name: "Seleccionar todos los libros de esta página" })).toBeFocused()
  await page.waitForLoadState("networkidle")
  guard.allowConsole(SIGN_OUT_RSC_404)
  await tabTo(page, accountMenu(page, stack, "a"))
  await page.keyboard.press("Enter")
  await page.keyboard.press("End")
  await expect(page.getByRole("menuitem", { name: "Cerrar sesión" })).toBeFocused()
  await page.keyboard.press("Enter")
  await page.waitForURL((url) => url.pathname === "/login")
  save(info, "teclado", { tasks: ["alta", "búsqueda", "selección", "movimiento", "edición", "cierre de sesión"], input: "Tab, Shift+Tab, flechas, Space, Enter, texto; sin ratón" })
})

